"""Turn one unverified niche hypothesis into a human/LLM editorial assignment."""
from __future__ import annotations

from .portfolio import score


def draft_assignment(row: dict) -> str:
    """A prompt for scene discovery, not an automatically publishable offer."""
    return f'''# Исследовательское задание: {row['name']}

**Номер:** {row['id']}  
**Статус:** гипотеза. Наличие исполнителя, спрос, цены и договоры не подтверждены.  
**Предварительная оценка:** {score(row)}/100, субъективная, не прогноз выручки.

## Исходная человеческая ситуация

{row['human_situation']}

## Гипотеза дохода

{row['economic_model']}

## Работа по сценам

Для этой ниши предложи от трёх до семи **различных** человеческих ситуаций.
Каждую описывай по шести полям:

1. Какая потребность возникла и почему именно сейчас?
2. Что человек уже знает и в чём сомневается?
3. Какой профессиональный признак здесь действительно отличает правильное решение?
4. Какие сведения необходимо спросить до передачи исполнителю?
5. Как выглядит честный маршрут: уточнение → согласование → компетентный исполнитель?
6. Какой вопрос естественным образом ведёт к прямому контакту?

Не делай страницы из перестановок ключевых слов. Не выдумывай цены, отзывы,
наличие товара, мастеров, партнёров, офис, сроки, лицензии или географию.
Не утверждай, что профессиональные услуги уже доступны: исполнитель ещё не проверен.
Исключи массовый публикационный выход: это **исследовательский черновик**.

## Полевые проверки до публикации

- Найти и подтвердить квалификацию и готовность хотя бы одного реального исполнителя.
- Сверить несколько запросов с реальными словами клиентов.
- Проверить существенные требования, риски, условия сделки и модель вознаграждения.
- Сформулировать одну самостоятельную полезную страницу, имеющую смысл и без поисковика.
- Лишь затем подготовить конфигурацию сайта со статусом publish и подтверждениями.
'''
